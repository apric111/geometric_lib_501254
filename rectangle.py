def area(a, b):
    '''
    Returns the area of the rectangle.

        Parameters:
            a (float), b (float): the lengths of the sides of the rectangle
        
        Return value:
            a * b (float): the area of a rectangle with sides a and b
    ''' 
    return a * b 

def perimeter(a, b): 
    '''
    Returns the perimeter of the rectangle.

        Parameters:
            a (float), b (float): the lengths of the sides of the rectangle
        
        Return value:
            (a + b) * 2 (float): the perimeter of the rectangle with sides a and b
    ''' 
    return (a + b) * 2
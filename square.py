
def area(a):
    '''
    Returns the area of a square.

        Parameters:
            a (float): the length of the side of the square
        
        Return value:
            a * a (float): the area of the square with side a
    '''
    return a * a


def perimeter(a):
    '''
    Returns the perimeter of the square.

        Parameters:
            a (float): the length of the side of the square
        
        Return value:
            4 * a (float): the perimeter of the square with side a
    '''
    return 4 * a
